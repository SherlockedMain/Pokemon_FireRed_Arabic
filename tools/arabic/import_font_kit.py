#!/usr/bin/env python3
"""Import the 8x16 Arabic font kit (from the BN1 / Crystal translations) into FireRed.

- Draws every glyph from arabic_font_kit/glyphs/regular into the normal, male
  and female font sheets on the extra-symbol page, from F9 18 upward.
- Replaces the Arabic block at the end of charmap.txt.
- Writes arabic_widths.json (then run apply_widths.py).

Glyph placement for a proportional right-to-left font:
- the kit cell is cropped to its ink columns;
- glyphs that join on the left (initial/medial forms, packed ال) get no gap
  on the left; everything else gets 1 blank column there (the space before
  the next letter);
- glyphs that do not join on the right keep their shadow column on the right.
Rows 2-15 of the 16px kit cell become FireRed's 14 glyph rows.
"""
import json, os, re, unicodedata
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
KIT = os.path.join(HERE, 'arabic_font_kit')
SHEETS = ['latin_normal', 'latin_male', 'latin_female']
CODES = json.load(open(os.path.join(HERE, 'arabic_codes.json')))   # single-byte codes free for Arabic
# Each Arabic glyph takes ONE byte (a code the English game never prints), so a
# 10-byte Pokémon name holds 10 Arabic letters. See arabic_codes.json.
ROW_OFFSET, GLYPH_ROWS = 2, 14
KIT_TO_FR = {0: 3, 1: 3, 2: 2, 3: 1}        # kit: 1 bg, 2 shadow, 3 ink -> FR: 3 bg, 2 shadow, 1 ink
BLOCK_MARK = '@ ---- Arabic glyphs (generated by tools/arabic/import_font_kit.py) ----'
OLD_MARK = '@ Arabic presentation forms (placeholder font) - extra symbol page'

def joins(cp):
    name = unicodedata.name(chr(cp), '')
    left = 'INITIAL FORM' in name or 'MEDIAL FORM' in name or cp == 0xE0A0
    right = 'FINAL FORM' in name or 'MEDIAL FORM' in name
    return left, right

def condense(cell, keep_min=4, max_cut=2):
    """Small font only: drop up to max_cut columns that repeat their right-hand
    neighbour (a stretch of the joining stroke), so words get narrower while
    every letter keeps its shape. The battle HUD fits 50 px per name."""
    cols = [list(c) for c in zip(*cell)]
    cut, j = 0, 1
    while j < len(cols) - 1 and cut < max_cut and len(cols) > keep_min:
        if cols[j] == cols[j + 1] and any(v in (1, 2) for v in cols[j]):
            del cols[j]
            cut += 1
        else:
            j += 1
    return [list(r) for r in zip(*cols)]

def build_cell(src, cp, row_offset, rows, max_width):
    ink_cols = [x for x in range(8) if any(src[x, y] == 3 for y in range(16))]
    l, r = min(ink_cols), max(ink_cols)
    jl, jr = joins(cp)
    right = r + 1 if (not jr and r + 1 < 8 and any(src[r + 1, y] == 2 for y in range(16))) else r
    cols = ([None] if not jl else []) + list(range(l, right + 1))
    while len(cols) > max_width:                       # small font cells are 8px: drop gap/shadow first
        cols.pop(0 if cols[0] is None else -1)
    return [[3 if c is None else KIT_TO_FR[src[c, y + row_offset]] if y + row_offset < 16 else 3
             for c in cols] for y in range(rows)]

# Small font (latin_small.png): 8x16 cells, 32 per row, 13 glyph rows. Kit rows
# 3-15 are used so nothing is clipped (baseline sits 1px higher than in the
# normal font).
SMALL_SHEET, SMALL_ROW_OFFSET, SMALL_ROWS = 'latin_small', 3, 13

def main():
    gmap = json.load(open(os.path.join(KIT, 'glyph_map.json')))
    entries = sorted(gmap.items(), key=lambda kv: kv[1]['atlas_index'])
    assert len(entries) <= len(CODES), '%d glyphs, %d free codes' % (len(entries), len(CODES))

    cells, small_cells = {}, {}
    for i, (key, info) in enumerate(entries):
        cp = int(key[2:], 16)
        src = Image.open(os.path.join(KIT, info['regular'])).load()
        cells[CODES[i]] = (cp, build_cell(src, cp, ROW_OFFSET, GLYPH_ROWS, 16))
        small_cells[CODES[i]] = (cp, condense(build_cell(src, cp, SMALL_ROW_OFFSET, SMALL_ROWS, 8)))

    for name in SHEETS:
        path = os.path.join(ROOT, 'graphics', 'fonts', name + '.png')
        sheet = Image.open(path); px = sheet.load()
        for gid in cells:                                   # clear the target cells first
            cx, cy = (gid % 16) * 16, (gid // 16) * 16
            for y in range(16):
                for x in range(16):
                    px[cx + x, cy + y] = 0
        for gid, (cp, cell) in cells.items():
            cx, cy = (gid % 16) * 16, (gid // 16) * 16
            for y in range(GLYPH_ROWS):
                for x, v in enumerate(cell[y]):
                    px[cx + x, cy + y] = v
        sheet.save(path)

    path = os.path.join(ROOT, 'graphics', 'fonts', SMALL_SHEET + '.png')
    sheet = Image.open(path); px = sheet.load()
    for gid in small_cells:
        cx, cy = (gid % 32) * 8, (gid // 32) * 16
        for y in range(16):
            for x in range(8):
                px[cx + x, cy + y] = 0
    for gid, (cp, cell) in small_cells.items():
        cx, cy = (gid % 32) * 8, (gid // 32) * 16
        for y in range(SMALL_ROWS):
            for x, v in enumerate(cell[y]):
                px[cx + x, cy + y] = v
    sheet.save(path)

    cm_path = os.path.join(ROOT, 'charmap.txt')
    cm = open(cm_path, encoding='utf-8').read()
    for mark in (BLOCK_MARK, OLD_MARK):
        if mark in cm:
            cm = cm[:cm.index(mark)].rstrip('\n') + '\n'
    lines = ['', BLOCK_MARK]
    for code, (cp, _) in cells.items():
        name = unicodedata.name(chr(cp), 'PRIVATE USE: font-kit helper glyph')
        lines.append("'%s' = %02X @ U+%04X %s" % (chr(cp), code, cp, name))
    open(cm_path, 'w', encoding='utf-8').write(cm + '\n'.join(lines) + '\n')

    json.dump({'normal': {str(g): len(c[0]) for g, (_, c) in cells.items()},
               'small': {str(g): len(c[0]) for g, (_, c) in small_cells.items()}},
              open(os.path.join(HERE, 'arabic_widths.json'), 'w'), indent=0)
    bitmap = [0] * 32
    for code in cells:
        bitmap[code >> 3] |= 1 << (code & 7)
    open(os.path.join(ROOT, 'include', 'arabic_codes.h'), 'w').write(
        '// Generated by tools/arabic/import_font_kit.py: single-byte codes holding Arabic glyphs.\n'
        '#ifndef GUARD_ARABIC_CODES_H\n#define GUARD_ARABIC_CODES_H\n\n'
        'static const u8 sArabicCodeBitmap[32] = {\n    '
        + ', '.join('0x%02X' % b for b in bitmap) + ',\n};\n\n'
        '#define IS_ARABIC_CODE(c) ((sArabicCodeBitmap[(c) >> 3] >> ((c) & 7)) & 1)\n\n#endif\n')
    print('imported %d glyphs into single-byte codes' % len(cells))

if __name__ == '__main__':
    main()
