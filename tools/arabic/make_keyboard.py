#!/usr/bin/env python3
"""Generate include/arabic_shaping.h: letter forms, joining rules, lam-alef
ligatures, the reverse map (shaped glyph -> base letter) and the Arabic
keyboard pages for the naming screen. Codes come from charmap.txt."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))

# base letter: (isolated, final, initial, medial) presentation forms; None = form does not exist
F = {
 'ء': (0xFE80, None, None, None), 'آ': (0xFE81, 0xFE82, None, None), 'أ': (0xFE83, 0xFE84, None, None),
 'ؤ': (0xFE85, 0xFE86, None, None), 'إ': (0xFE87, 0xFE88, None, None), 'ئ': (0xFE89, 0xFE8A, 0xFE8B, 0xFE8C),
 'ا': (0xFE8D, 0xFE8E, None, None), 'ب': (0xFE8F, 0xFE90, 0xFE91, 0xFE92), 'ة': (0xFE93, 0xFE94, None, None),
 'ت': (0xFE95, 0xFE96, 0xFE97, 0xFE98), 'ث': (0xFE99, 0xFE9A, 0xFE9B, 0xFE9C), 'ج': (0xFE9D, 0xFE9E, 0xFE9F, 0xFEA0),
 'ح': (0xFEA1, 0xFEA2, 0xFEA3, 0xFEA4), 'خ': (0xFEA5, 0xFEA6, 0xFEA7, 0xFEA8), 'د': (0xFEA9, 0xFEAA, None, None),
 'ذ': (0xFEAB, 0xFEAC, None, None), 'ر': (0xFEAD, 0xFEAE, None, None), 'ز': (0xFEAF, 0xFEB0, None, None),
 'س': (0xFEB1, 0xFEB2, 0xFEB3, 0xFEB4), 'ش': (0xFEB5, 0xFEB6, 0xFEB7, 0xFEB8), 'ص': (0xFEB9, 0xFEBA, 0xFEBB, 0xFEBC),
 'ض': (0xFEBD, 0xFEBE, 0xFEBF, 0xFEC0), 'ط': (0xFEC1, 0xFEC2, 0xFEC3, 0xFEC4), 'ظ': (0xFEC5, 0xFEC6, 0xFEC7, 0xFEC8),
 'ع': (0xFEC9, 0xFECA, 0xFECB, 0xFECC), 'غ': (0xFECD, 0xFECE, 0xFECF, 0xFED0), 'ف': (0xFED1, 0xFED2, 0xFED3, 0xFED4),
 'ق': (0xFED5, 0xFED6, 0xFED7, 0xFED8), 'ك': (0xFED9, 0xFEDA, 0xFEDB, 0xFEDC), 'ل': (0xFEDD, 0xFEDE, 0xFEDF, 0xFEE0),
 'م': (0xFEE1, 0xFEE2, 0xFEE3, 0xFEE4), 'ن': (0xFEE5, 0xFEE6, 0xFEE7, 0xFEE8), 'ه': (0xFEE9, 0xFEEA, 0xFEEB, 0xFEEC),
 'و': (0xFEED, 0xFEEE, None, None), 'ى': (0xFEEF, 0xFEF0, None, None), 'ي': (0xFEF1, 0xFEF2, 0xFEF3, 0xFEF4),
}
LAMALEF = {'آ': (0xFEF5, 0xFEF6), 'أ': (0xFEF7, 0xFEF8), 'إ': (0xFEF9, 0xFEFA), 'ا': (0xFEFB, 0xFEFC)}  # isolated, final

# Keyboard pages, read right to left (column 7 is the first key of a row).
LETTERS = ['ابتثجحخد', 'ذرزسشصضط', 'ظعغفقكلم', 'نهويةىء ']
EXTRAS = ['أإآؤئ!', '01234؟', '56789.', '♂♀-…،\'']   # 6 columns

def charmap():
    cm = {}
    for line in open(os.path.join(ROOT, 'charmap.txt'), encoding='utf-8'):
        l = line.split('@')[0].strip()
        m = re.match(r"^'(.+)'\s*=\s*([0-9A-F]{2})$", l)
        if m and len(m.group(1)) == 1:
            cm.setdefault(m.group(1), int(m.group(2), 16))
        elif l.startswith("'\\''") or l.startswith("'''"):
            pass
    return cm

def main():
    cm = charmap()
    code = lambda cp: cm[chr(cp)] if cp is not None else 0
    letters = list(F)
    rows = []
    for ch in letters:
        iso, fin, ini, med = F[ch]
        dual = ini is not None
        rows.append((code(iso), code(fin), code(ini), code(med), 1 if dual else 0, 1 if ch == 'ء' else 0))
    rev = [0xFF] * 256          # glyph code -> letter index
    for i, ch in enumerate(letters):
        for cp in F[ch]:
            if cp is not None:
                rev[cm[chr(cp)]] = i
    lam = letters.index('ل')
    lig = []
    for ch, (iso, fin) in LAMALEF.items():
        lig.append((letters.index(ch), cm[chr(iso)], cm[chr(fin)]))
    def keycode(c):
        if c == ' ':
            return 0x00
        if c in F:
            return cm[chr(F[c][0])]
        return cm[c] if c != "'" else 0xB4
    kb = [[keycode(r[7 - i]) if len(r) == 8 else 0 for i in range(8)] for r in LETTERS]
    kb2 = [[keycode(c) for c in r] for r in EXTRAS]
    out = ['// Generated by tools/arabic/make_keyboard.py - do not edit.', '#ifndef GUARD_ARABIC_SHAPING_H',
           '#define GUARD_ARABIC_SHAPING_H', '',
           'struct ArabicLetter { u8 iso, fin, ini, med, dual, noJoin; };', '',
           '#define ARABIC_LETTER_COUNT %d' % len(letters), '#define ARABIC_LAM %d' % lam, '',
           'static const struct ArabicLetter sArabicLetters[ARABIC_LETTER_COUNT] = {']
    for ch, r in zip(letters, rows):
        out.append('    {0x%02X, 0x%02X, 0x%02X, 0x%02X, %d, %d}, // %s' % (r + (ch,)))
    out += ['};', '', '// glyph code -> letter index (0xFF: not an Arabic letter)', 'static const u8 sArabicLetterOf[256] = {']
    for i in range(0, 256, 16):
        out.append('    ' + ', '.join('0x%02X' % v for v in rev[i:i + 16]) + ',')
    out += ['};', '', '// lam + alef ligatures: {alef letter index, isolated code, final code}',
            'static const u8 sArabicLamAlef[%d][3] = {' % len(lig)]
    out += ['    {%d, 0x%02X, 0x%02X},' % t for t in lig]
    out += ['};', '', '// Naming screen: Arabic letters page (right to left) and extras page',
            'static const u8 sArabicKeyboard[4][8] = {']
    out += ['    {' + ', '.join('0x%02X' % v for v in r) + '},' for r in kb]
    out += ['};', 'static const u8 sArabicKeyboardExtras[4][6] = {']
    out += ['    {' + ', '.join('0x%02X' % v for v in r) + '},' for r in kb2]
    out += ['};', '', '#endif', '']
    open(os.path.join(ROOT, 'include', 'arabic_shaping.h'), 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote include/arabic_shaping.h: %d letters, %d ligatures' % (len(letters), len(lig)))

if __name__ == '__main__':
    main()
